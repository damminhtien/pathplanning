from .renderers.mindmap import map_page


def build_sitemap(
    planners: list[dict[str, Any]], datasets: list[dict[str, Any]], today: str
) -> str:
    namespace = "http://www.sitemaps.org/schemas/sitemap/0.9"
    ET.register_namespace("", namespace)
    root = ET.Element(f"{{{namespace}}}urlset")
    urls = [f"{BASE_URL}/", f"{BASE_URL}/mindmap/"]
    urls.extend(f"{BASE_URL}/algorithms/{planner['id']}/" for planner in planners)
    urls.append(f"{BASE_URL}/datasets/")
    urls.extend(f"{BASE_URL}/datasets/{dataset['id']}/" for dataset in datasets)
    urls.append(f"{BASE_URL}/case-studies/")
    for url in urls:
        entry = ET.SubElement(root, f"{{{namespace}}}url")
        ET.SubElement(entry, f"{{{namespace}}}loc").text = url
        ET.SubElement(entry, f"{{{namespace}}}lastmod").text = today
    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode", xml_declaration=True) + "\n"


def prepare_output(output: Path) -> Path:
    output = output.resolve()
    if output in (WEBSITE_ROOT, PROJECT_ROOT, Path("/")):
        raise SystemExit(f"Refusing to use a source directory as output: {output}")
    if output.exists():
        if output.is_symlink() or not (output / BUILD_MARKER).is_file():
            raise SystemExit(f"Output exists and is not owned by this builder: {output}")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / BUILD_MARKER).write_text("Generated by website/build_site.py\n", encoding="utf-8")
    return output


def copy_static_files(output: Path) -> None:
    for name in (
        "index.html",
        "app.js",
        "mathjax-config.js",
        "styles.css",
        "theme.css",
        "three-dimensional.css",
        "planner-runs.css",
        "favicon.svg",
        "og-image.png",
        "og-image.svg",
        "404.html",
        "robots.txt",
    ):
        shutil.copy2(WEBSITE_ROOT / name, output / name)
    shutil.copytree(WEBSITE_ROOT / "data", output / "data")
    shutil.copytree(WEBSITE_ROOT / "scripts", output / "scripts")
    for name in ("learning.css", "mindmap.css", "mindmap.js", "datasets.css", "case-studies.css"):
        shutil.copy2(WEBSITE_ROOT / name, output / name)


def render_home(content: SiteContent) -> str:
    """Fill the small set of data-bound slots in the hand-authored home page."""
    home = (WEBSITE_ROOT / "index.html").read_text(encoding="utf-8")
    catalog_marker = "<!-- generated:planner-cards -->"
    if home.count(catalog_marker) != 1:
        raise SystemExit("The home page must contain exactly one planner-card marker.")

    counts: dict[str, int] = {kind: 0 for kind in FAMILY_LABELS}
    for planner in content.planners:
        counts[planner["kind"]] += 1
    home = home.replace("{{PLANNER_COUNT}}", str(len(content.planners)))
    home = home.replace("{{FAMILY_COUNT}}", str(len(FAMILY_LABELS)))
    home = home.replace(catalog_marker, render_static_catalog(content.planners))
    applications_marker = "<!-- generated:application-cards -->"
    if home.count(applications_marker) != 1:
        raise SystemExit("The home page must contain exactly one application-card marker.")
    home = home.replace(
        applications_marker, render_home_applications(content.applications["overview"])
    )
    case_studies_marker = "<!-- generated:case-study-cards -->"
    if home.count(case_studies_marker) != 1:
        raise SystemExit("The home page must contain exactly one case-study-card marker.")
    home = home.replace(case_studies_marker, render_home_case_studies(content.case_studies))
    filters_marker = "<!-- generated:planner-family-filters -->"
    if home.count(filters_marker) != 1:
        raise SystemExit("The home page must contain exactly one planner-family filter marker.")
    filters = []
    for kind, label in FAMILY_LABELS.items():
        filters.append(
            f'<button class="filter-chip" type="button" data-filter="{html.escape(kind, quote=True)}">'
            f"{html.escape(label)} <span>{counts[kind]}</span></button>"
        )
    home = home.replace(filters_marker, "\n            ".join(filters))
    if re.search(r"\{\{[A-Z_]+\}\}", home):
        raise SystemExit("The home page contains an unfilled data placeholder.")
    return home


def build(output: Path) -> int:
    content = load_site_content()
    output = prepare_output(output)
    copy_static_files(output)

    (output / "index.html").write_text(render_home(content), encoding="utf-8")
    today = dt.datetime.now(dt.timezone.utc).date().isoformat()
    (output / "sitemap.xml").write_text(
        build_sitemap(content.planners, content.datasets, today), encoding="utf-8"
    )

    planner_by_id = {planner["id"]: planner for planner in content.planners}
    planner_positions = {
        planner["id"]: index for index, planner in enumerate(content.planners, start=1)
    }
    for planner in content.planners:
        page_dir = output / "algorithms" / planner["id"]
        page_dir.mkdir(parents=True)
        page_file = page_dir / "index.html"
        page_file.write_text(
            lesson_page(
                planner,
                content.lessons[planner["id"]],
                content.analyses[planner["id"]],
                content.references[planner["id"]],
                content.registry_rows[planner["id"]],
                content.applications["families"][planner["kind"]],
                planner_by_id,
                planner_positions,
                len(content.planners),
                output,
                page_file,
            ),
            encoding="utf-8",
        )

    datasets_dir = output / "datasets"
    datasets_dir.mkdir()
    datasets_by_id = {dataset["id"]: dataset for dataset in content.datasets}
    index_file = datasets_dir / "index.html"
    index_file.write_text(
        dataset_index_page(
            content.datasets,
            content.dataset_snapshot,
            output,
            index_file,
        ),
        encoding="utf-8",
    )
    for dataset in content.datasets:
        page_dir = datasets_dir / dataset["id"]
        page_dir.mkdir()
        page_file = page_dir / "index.html"
        page_file.write_text(
            dataset_detail_page(
                dataset,
                datasets_by_id,
                content.dataset_snapshot,
                output,
                page_file,
            ),
            encoding="utf-8",
        )

    case_studies_dir = output / "case-studies"
    case_studies_dir.mkdir()
    case_studies_file = case_studies_dir / "index.html"
    case_studies_file.write_text(
        case_studies_page(content.case_studies, output, case_studies_file),
        encoding="utf-8",
    )

    expanded_map = expand_project_map(content.project_map, content.planners, content.registry_rows)
    map_dir = output / "mindmap"
    map_dir.mkdir()
    (map_dir / "index.html").write_text(
        map_page(expanded_map, len(content.planners)), encoding="utf-8"
    )
    print(
        f"Built the home page, project mind map, and {len(content.planners)} "
        f"planner lessons, {len(content.datasets)} dataset profiles, and "
        f"{len(content.case_studies)} case studies in {output}"
    )
    return len(content.planners)
